// 編集ベースの生成プロンプト。
//
// **マスターはフィジビリ実コード** scripts/avatar-generation/prompt-builder.ts の STYLE_FIXED_CLAUSES ＋
// buildPrompt の変数。そこに design.md（＝要件）の更新箇所だけを乗せる。由来のない指示は足さない。
//
// 更新箇所（マスターに乗せる差分）:
//   - 参照画像 → seed を編集の元にする（Req 3.1）
//   - 「白髪も黒で塗る」→ 白髪は筋のストローク（Req 3.4）
//   - 「線画にしない・黒一色」→ seed の細い線描（襟・ボタン・眼鏡）には一致（Req 5.2）
//   - 「顔の輪郭線を一切描かない」→ 顔・顎の輪郭は seed に準じる（Req 5.3）
//   - 追加: 年齢はシルエットで表す（Req 3.3）／スケールは zoom＋目線のみ seed 一致（Req 4.1・4.2）
//
// **要件の穴の補い**: Req 3.1 の文言「編集の元画像として与え、別個体を生成する」は「seed を土台に
// 別個体を生成する」としか読めず、「seed を編集して枠を保つ」を強制していない（＝スケール狂いの根）。
// 要件の書き直しは別途要るが、まずプロンプトで **seed の in-place 編集＋枠の保持** を明示して塞ぐ。

import type { Variation } from './avatar-variation.js';

/** プロンプトの入力。可変軸（Variation）に、persona 由来の年齢・職業を足したもの。 */
export interface AvatarVariation extends Variation {
	age: number;
	occupation: string;
}

// マスター（prompt-builder.ts）の glasses 文言。
const glassesInstruction = (glasses: boolean): string =>
	glasses ? 'あり（黒いフレームのみをシルエットで描き、レンズ内・目は描かない）' : 'なし';

export const buildAvatarPrompt = (v: AvatarVariation): string =>
	[
		'# 指示',
		// seed の in-place 編集を命じ、枠を保つことでスケールを構造的に担保する（Req 3.1 の穴を塞ぐ）。
		'これは画像編集の指示。添付した seed 画像を編集して出力を作る（白紙から新しく描き起こさない）。seed の枠——画角・頭の大きさ（ズーム）・目線の高さ・頭の位置——はそのまま保ち、その枠の中で人物を別人に差し替え、下の「描き分ける」の指定値を反映する。',
		'',
		'# 様式（seed に一致させる）',
		// マスター clause1 ＋ Req 5.2（seed の細い線描に一致）。
		'- 髪・衣服・体の輪郭は黒基調でベタ塗りのシルエットにする（グレー・写実的な陰影にしない）。seed に含まれる襟・ボタン・眼鏡などの細い線描には一致させる。',
		// マスター clause1「白髪も黒で塗る」→ Req 3.4。
		// '- 白髪は黒で塗らず、筋のストロークで描く。',
		// マスター clause2 ＋ clause3。
		'- 顔・首・肌は塗らず白のまま残し、featureless にする。目・鼻・口・眉・まつげを描かず、顔の内側は白のネガティブスペースにする。',
		// マスター clause3「顔の輪郭線を一切描かない」→ Req 5.3（輪郭は seed 準拠）。
		// '- 顔・顎の輪郭線は seed の描き方に準じる。',
		// マスター clause4 ＋ 影/ドロップシャドウ明示（Req 5.6）。
		'- 背景は無地の白一色にする（グラデーション・小物・枠を置かない）。影・ドロップシャドウを描かない。',
		// マスター clause5。
		// '- 構図はバストアップ（胸から上）にし、正方1:1の枠に収める。',
		// マスター clause6。
		'- 全体をアイコン的に単純化する（写実的な描き込み・テクスチャ・柄を避ける）。',
		'',
		'# スケール（seed の枠を保つ。ここが崩れると一覧で不揃いになる）',
		// Req 4.1: 固定は zoom+目線のみ。
		// '- 固定するのは seed の枠＝ズーム（頭の大きさ）と目線の高さ。ここは seed と完全に一致させる。',
		// Req 4.2: 体型・髪型・ポーズは枠の中で変える。
		// '- 体型・髪型・ポーズは枠を保ったまま、下の指定値どおりに変える（枠だけ保ち、中身は変える）。',
		'',
		'# 描き分ける（指定値で変える）',
		// マスターの変数「年齢帯」＋ Req 3.3（シルエットで表す）。
		`- 年齢: ${v.age}歳。皺や灰色でなく、頭身（頭と体の比率）・生え際・姿勢・髪型のシルエットで表す。`,
		`- 髪型: ${v.hair}`,
		`- 体型: ${v.body}`,
		`- ポーズ: ${v.pose}`,
		`- アングル: ${v.angle}`,
		`- 服装: ${v.occupation}にふさわしい服装`,
		`- メガネ: ${glassesInstruction(v.glasses)}`,
		// マスターの様式固定文「表情は話している最中の真剣な様子」。
		'- 表情は話している最中の真剣な様子にする（笑顔にしない）。'
	].join('\n');
