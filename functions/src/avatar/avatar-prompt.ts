// 編集ベースの生成プロンプト（**唯一のプロンプト定義**。verify も本番もこれを使う・Req 1.4）。
//
// 3.1 の編集で「別人だが seed の頭サイズ・目線・様式は保つ」ことを確かめた結果を反映
// （検証は verify-avatar-edit.ts が本エンジン経由で行う）。学んだ制約:
//   - 向き（アングル）は seed から引き継がれるので、言葉で指示しない。向きの変更は局所編集で済まず
//     新規生成に倒れてスケールが崩れる。体型・ポーズなどシルエットを作り替える指定もしない。
//   - 「枠」「上半身」という曖昧・誘発語を使わない。保つ対象は「頭の大きさ」「目線の高さ」「様式」を具体語で。
//   - 変えるのは編集で済む範囲（髪型・服装・メガネ）だけ。

import type { Variation } from './avatar-variation.js';

/** プロンプトの入力。可変軸（Variation）に、persona 由来の年齢・職業を足したもの。 */
export interface AvatarVariation extends Variation {
	age: number;
	occupation: string;
}

export const buildAvatarPrompt = (v: AvatarVariation): string => {
	const lines = [
		'これは画像編集の指示。添付した画像を編集して、別人のアバターにする。次を必ず守る。',
		'- 出力は正方形（縦と横が同じ長さ）の画像にする。',
		'- 頭の大きさ（画面に占める頭のサイズ）と目線の高さを、元画像と同じにする。',
		'- 様式は元画像のまま保つ：黒基調のシルエット、顔は描かない（目・鼻・口・眉を描かず白のネガティブスペース）、背景は白一色、影は描かない。',
		'- 髪・衣服・体の輪郭は黒基調でベタ塗りのシルエットにする（グレー・写実的な陰影にしない）。'
	];
	// 白髪は senior 以上（50歳〜）のみ。middle 以下には白い筋を入れさせない。
	if (v.age >= 50) {
		lines.push('- 白髪は、髪を黒く塗ったうえに白い細い筋（毛流れ）を入れて表す。');
	}
	lines.push(
		`- 変えるのは人物を別人にすることと、次だけ：髪型を「${v.hair}」にする / 服装を「${v.occupation}にふさわしい服」にする / メガネ${v.glasses ? 'をかける（黒いフレームのみ・レンズ内と目は描かない）' : 'はかけない'}`
	);
	return lines.join('\n');
};
