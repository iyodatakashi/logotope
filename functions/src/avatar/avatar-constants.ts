// アバター生成で「効く」数値の**単一定義**。
//
// これらの値は先行フィジビリ persona-avatar-image-generation では生成物のピクセルや
// postprocess.py の中にしか無く、再現不能だった（本 spec の Req 1.2 が解決対象）。
// ここに値・測定元・根拠をコードとして固定し、seed 生成・後処理・プロンプトはこの1箇所を参照する。
// 「ピクセルにのみ存在する数値」をゼロにするのが目的なので、同じ数値を各所で再定義しない。

/**
 * 出力アセットの一辺（正方 px）。仕様で 256×256 に固定（Req 2.3 / 6.4）。
 * 出所: 仕様。
 */
export const ASSET_SIZE = 256;

/**
 * seed キャンバスの一辺。アセットと同一にする。
 * seed と最終アセットで枠がぶれると、seed を編集して作る生成物の枠もぶれるため、同じ値に束ねる。
 */
export const SEED_CANVAS = ASSET_SIZE;

/**
 * 被写体の縦占有（キャンバス縦に対する比率）。下端接地・下余白0で、余白は上のみに残る。
 * 出所: 先行フィジビリ validation の採用結論（0.92）。
 * 却下値の 0.855（下余白 0.063）は根拠に用いない（steering に残る旧値も不採用・Req adjacent）。
 */
export const SUBJECT_HEIGHT_RATIO = 0.92;

/**
 * 輝度→アルファ反転後、これ未満のアルファ（0–255）は透明に落とす。
 * ＝薄いドロップシャドウ・背景のにじみの除去しきい値。
 * 出所: postprocess.py の SHADOW_CUTOFF と同値（ゴールデン等価のため一致必須）。
 */
export const SHADOW_CUTOFF = 36;

/**
 * 生成する画像の絶対サイズ（正方・px）。
 *
 * スケールの唯一の基準を「顔の高さ＝画像高の FACE_HEIGHT_PERCENT%」で与えるが、**比率だけでは
 * 画像高が不定で効かない**（先行フィジビリの結論）。効かせるには画像高を具体値で固定する必要がある。
 * 値自体は最終結果を変えない（後処理が被写体を ASSET_SIZE へ縮約し、最終比率は顔/被写体bbox で決まる）。
 * これはモデル挙動を安定させるための絶対アンカーで、1024 は縮約の余裕（256 の4倍）を持つ標準値。
 */
export const GENERATION_IMAGE_SIZE = 1024;

/**
 * 生成時に固定する顔の高さ（GENERATION_IMAGE_SIZE に対する％）。**仮値**。
 *
 * 「顔」の測定境界は現状 **生え際〜顎の先** を採る（頭頂〜顎／眉〜顎 だと同じ 45% でも大きさが変わる）。
 * 境界と値は 2.5 検証（tasks 4.2）で確定する。プロンプトは GENERATION_IMAGE_SIZE × この％を
 * 絶対 px（≈461px）に落として指示する。単一定義なので調整はこの1箇所で済む。
 */
export const FACE_HEIGHT_PERCENT = 45;
